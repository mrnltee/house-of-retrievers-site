// Imports HOR's supplied breed icons from public/dog-breeds-icons/svg into
// public/breeds/<key>.svg and writes the breed list (app/lib/breedList.mjs).
// Run: node scripts/breed-icons/import.mjs   (after adding or replacing icons there)
// Keys already saved on registrations and people never change: the supplied
// file names below are mapped onto them. A breed keeps its old icon if the
// folder has none for it (e.g. Dalmatian).
import { copyFileSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { checkBreedIconSvg } from "../../app/lib/breedIcons.mjs";

const SOURCE = "public/dog-breeds-icons/svg";
// Supplied file → the key already in use (and its label).
const EXISTING = {
  "aspin-asong-pinoy": ["aspin", "Aspin / Asong Pinoy"],
  "akita-inu": ["akita", "Akita Inu"],
  "pembroke-welsh-corgi": ["corgi", "Pembroke Welsh Corgi"],
  "american-pit-bull-terrier": ["pit-bull", "American Pit Bull Terrier"],
  "standard-poodle": ["poodle", "Standard Poodle"],
};
// Breeds kept from the first set that the folder doesn't include.
const KEPT = [["dalmatian", "Dalmatian"]];
const LABELS = {
  "shih-tzu": "Shih Tzu", "lhasa-apso": "Lhasa Apso", "bichon-frise": "Bichon Frise", "chinese-shar-pei": "Chinese Shar-Pei",
  "coton-de-tulear": "Coton de Tulear", "bouvier-des-flandres": "Bouvier des Flandres", lowchen: "Löwchen", "cesky-terrier": "Český Terrier",
  "danish-swedish-farmdog": "Danish-Swedish Farmdog", "black-and-tan-coonhound": "Black and Tan Coonhound",
  "irish-red-and-white-setter": "Irish Red and White Setter", "glen-of-imaal-terrier": "Glen of Imaal Terrier",
  "saint-bernard": "Saint Bernard", "jack-russell-terrier": "Jack Russell Terrier", "cavalier-king-charles-spaniel": "Cavalier King Charles Spaniel",
};
const SMALL = new Set(["and", "of", "de", "des", "the"]);
const titleCase = (slug) => slug.split("-").map((w, i) => (i && SMALL.has(w) ? w : w[0].toUpperCase() + w.slice(1))).join(" ");

const breeds = [];
for (const file of readdirSync(SOURCE).filter((f) => f.endsWith(".svg")).sort()) {
  const slug = file.replace(/\.svg$/, "");
  const svg = readFileSync(`${SOURCE}/${file}`, "utf8");
  const check = checkBreedIconSvg(svg);
  if (check.error) throw new Error(`${file}: ${check.error}`);
  const [key, label] = EXISTING[slug] || [slug, LABELS[slug] || titleCase(slug)];
  copyFileSync(`${SOURCE}/${file}`, `public/breeds/${key}.svg`);
  breeds.push({ key, label, icon: true });
}
for (const [key, label] of KEPT) if (!breeds.some((b) => b.key === key)) breeds.push({ key, label, icon: true });
// The most common here first (HOR's pick), then A–Z, then "Other".
const FIRST = ["aspin", "golden-retriever", "labrador-retriever"];
const top = FIRST.map((key) => breeds.find((b) => b.key === key)).filter(Boolean);
const rest = breeds.filter((b) => !FIRST.includes(b.key)).sort((a, b) => a.label.localeCompare(b.label, "en"));
const list = [...top, ...rest, { key: "other", label: "Other / not sure", icon: false }];
writeFileSync("app/lib/breedList.mjs", `// Generated by scripts/breed-icons/import.mjs from public/dog-breeds-icons/svg. Don't edit by hand; rerun the script.\nexport const BREED_LIST = ${JSON.stringify(list, null, 2)};\n`);
console.log(`${list.length - 1} breeds with icons, plus Other.`);
